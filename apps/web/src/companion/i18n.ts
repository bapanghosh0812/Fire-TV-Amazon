const DICTS: Record<string, Dict> = { en, hi, es, fr, de, pt, ja, ar };

export type Key = keyof typeof en;

// A ?lang=hi link override helps demos; otherwise follow the phone's own language.
const requested = new URLSearchParams(location.search).get('lang') || navigator.language || 'en';
const base = requested.split('-')[0].toLowerCase();
export const uiLang = DICTS[base] ? base : 'en';
export const isRtl = uiLang === 'ar';
const dict = DICTS[uiLang];

export function t(key: Key, vars?: Record<string, string | number>) {
  let s: string = dict[key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function ideas(kind: 'world' | 'spark') {
  return t(kind === 'world' ? 'worldIdeas' : 'sparkIdeas').split('|');
}
